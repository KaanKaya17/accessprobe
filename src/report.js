import { aiPrompt } from './fixes.js';

const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const c = (code) => (s) => (tty ? `\x1b[${code}m${s}\x1b[0m` : String(s));
export const color = {
  red: c('31'),
  yellow: c('33'),
  green: c('32'),
  cyan: c('36'),
  dim: c('2'),
  bold: c('1'),
};

const SEV = {
  critical: { icon: '✖', paint: color.red, label: 'CRITICAL' },
  warning: { icon: '!', paint: color.yellow, label: 'WARNING' },
  info: { icon: 'i', paint: color.cyan, label: 'INFO' },
};

// stats are optional; without any tested table there is nothing to grade
export function grade(findings, stats) {
  if (stats && stats.tables === 0 && !findings.length) return 'N/A';
  const crit = findings.filter((f) => f.severity === 'critical').length;
  const warn = findings.filter((f) => f.severity === 'warning').length;
  if (crit >= 2) return 'F';
  if (crit === 1) return 'D';
  if (warn > 2) return 'C';
  if (warn > 0) return 'B';
  return 'A';
}

export function printReport(r, { wroteFile = false } = {}) {
  const out = [];
  const g = grade(r.findings, r.stats);
  const gp = g === 'A' ? color.green : g === 'B' || g === 'N/A' ? color.yellow : color.red;
  out.push('');
  out.push(color.bold(`rlsprobe report — ${r.target}`));
  out.push(`Grade: ${gp(color.bold(g))}   ${counts(r.findings)}`);
  out.push(color.dim(`${r.stats.tables} tables, ${r.stats.buckets} buckets, ${r.stats.rpcs} functions tested in ${r.stats.seconds}s`));
  out.push(coverageLine(r));
  if (g === 'N/A') out.push(color.yellow(color.bold('Nothing was tested — this is NOT a clean bill of health. See Notes.')));
  out.push('');

  const order = ['critical', 'warning', 'info'];
  const sorted = [...r.findings].sort((a, b) => order.indexOf(a.severity) - order.indexOf(b.severity));
  for (const f of sorted) {
    const s = SEV[f.severity];
    out.push(`${s.paint(`${s.icon} ${s.label}`)}  ${color.bold(f.title)}`);
    out.push(`   ${f.detail}`);
    out.push(color.dim(`   proof: ${f.evidence}`));
    out.push('');
  }

  if (r.passed.length) {
    out.push(color.green(color.bold('Passed')));
    for (const p of r.passed) out.push(color.green(`  ✔ ${p.replace(/ ✔$/, '')}`));
    out.push('');
  }
  if (r.notes.length) {
    out.push(color.bold('Notes'));
    for (const n of r.notes) out.push(`  • ${n}`);
    out.push('');
  }
  if (!wroteFile && sorted.some((f) => f.fix)) {
    out.push(color.dim('Fix SQL and copy-paste AI prompts for each finding: run with --out report.md'));
  }
  console.log(out.join('\n'));
}

export function markdownReport(r) {
  const g = grade(r.findings, r.stats);
  const md = [];
  md.push(`# rlsprobe report`);
  md.push('');
  md.push(`**Target:** ${r.target}  `);
  md.push(`**Date:** ${r.date}  `);
  md.push(`**Grade:** ${g} — ${counts(r.findings)}`);
  md.push('');
  md.push(`Tested ${r.stats.tables} tables, ${r.stats.buckets} storage buckets, ${r.stats.rpcs} functions with two real test users (A and B).`);
  md.push(coverageLine(r, false));
  if (g === 'N/A') md.push('', '> ⚠️ **Nothing was tested — this is not a clean bill of health.** See Notes.');
  md.push('Every critical finding below was **proven** with a real request against data the test users created themselves.');
  md.push('');

  const order = ['critical', 'warning', 'info'];
  const sorted = [...r.findings].sort((a, b) => order.indexOf(a.severity) - order.indexOf(b.severity));
  sorted.forEach((f, i) => {
    md.push(`## ${i + 1}. [${f.severity.toUpperCase()}] ${f.title}`);
    md.push('');
    md.push(f.detail);
    md.push('');
    md.push(`**Proof:** \`${f.evidence.replace(/`/g, "'")}\``);
    md.push('');
    if (f.fix?.sql) {
      md.push('**Fix (SQL — run in Supabase SQL editor or as a migration):**');
      md.push('');
      md.push('```sql');
      md.push(f.fix.sql);
      md.push('```');
      md.push('');
    }
    if (f.fix?.steps?.length) {
      md.push('**Fix:**');
      md.push('');
      f.fix.steps.forEach((s) => md.push(`- ${s}`));
      md.push('');
    }
    if (f.severity !== 'info') {
      md.push('<details><summary>Prompt for Lovable / Bolt / Cursor / Claude Code</summary>');
      md.push('');
      md.push('```text');
      md.push(aiPrompt(f));
      md.push('```');
      md.push('');
      md.push('</details>');
      md.push('');
    }
  });

  if (r.passed.length) {
    md.push('## Passed checks');
    md.push('');
    r.passed.forEach((p) => md.push(`- ✔ ${p.replace(/ ✔$/, '')}`));
    md.push('');
  }
  if (r.notes.length) {
    md.push('## Notes');
    md.push('');
    r.notes.forEach((n) => md.push(`- ${n}`));
    md.push('');
  }
  md.push('---');
  md.push('Generated by [rlsprobe](https://github.com/) — only test apps you own.');
  return md.join('\n');
}

function coverageLine(r, paint = true) {
  const { tables, fullyTested, readOnly = 0 } = r.stats;
  if (!tables || fullyTested === undefined) return '';
  let line = `Coverage: ${fullyTested}/${tables} tables fully attacked (A wrote a row, B tried to read, change, forge and delete it)`;
  if (readOnly) line += `, ${readOnly} read-only for users`;
  if (!paint) return `${line}.`;
  return fullyTested + readOnly === tables ? color.green(line) : color.yellow(line);
}

function counts(findings) {
  const n = (s) => findings.filter((f) => f.severity === s).length;
  return `${n('critical')} critical, ${n('warning')} warnings, ${n('info')} info`;
}
